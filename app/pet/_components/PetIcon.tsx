// 소유자: C. 펫 화면 원형 버튼 안에 들어가는 아이콘 8개. (2026-08-26 사용자 시안)
//
// **이모지를 대신한다.** 전에는 버튼마다 이모지 한 자(🌿 🚪 📊 🏪 🌟 💬 ✅ 🤝)였고, 사용자가
// 손그림 느낌의 아이콘 4개(새싹 · 24H 상점 · 막대그래프 · ⓘ)를 주며 교체를 요청했다.
// 시안에 없는 넷(외출·커뮤니티·미션·모임)은 같은 규칙으로 새로 그렸다.
//
// 이모지를 뺀 것은 design.md 135행("이모지는 마스코트 자리에만 쓴다")에 오히려 가까워지는
// 방향이다 — 그 규칙은 이 화면이 예외로 깨고 있었고, 버튼 쪽만 규칙으로 돌아온다.
// **카드 제목(🍎 경험치 등)과 재화 줄(🌱❤️⭐)의 이모지는 그대로다** — 요청이 "버튼 내부"였다.
//
// ── 그리는 규칙 (시안에서 읽은 것) ──────────────────────────────────────────────
//  - 24 × 24 좌표계. 획은 굵고 둥글다(stroke-linecap·linejoin: round)
//  - 외곽선 한 겹 + 그 안에 부드러운 채색. 그림자·광택은 없다
//  - 채색은 사물 고유색이다(잎은 초록, 지붕은 노랑, 막대는 셋이 다른 색).
//    이 화면의 방 배경 SVG가 같은 방식을 쓴다(pet.css .pet-room__floor 등) — 종족색을
//    따르면 파란 잎·주황 하늘이 된다는 그 주석의 근거가 여기에도 그대로 적용된다
//  - **외곽선만은 종족색을 따른다**(pet.css .pet-icon). 시안은 갈색 한 벌이지만 그 게임은
//    팔레트가 하나이고, 이 앱은 종족이 셋이라 링(--pet-chip-ring)이 종족색이다.
//    외곽선을 갈색으로 고정하면 고양이(파랑)·곰(초록) 링 안에서 아이콘만 갈색으로 뜬다
//
// 색은 CSS가 준다(data-f 속성 → pet.css). 여기서 fill을 하드코딩하지 않는 이유는 방 배경
// SVG와 같다 — 색을 한 파일에 모아 두면 톤을 바꿀 때 한 곳만 본다.
//
// 장식이므로 <svg>에 aria-hidden이 붙는다. 버튼 이름은 그 옆 글자가 갖는다 —
// 방 안 액션 알약은 라벨이 버튼 안에 있고, 오른쪽 레일은 `.pet-rail__label`이 눈에만 접혀
// 있다(`display: none`이 아니라 폭 0이라 스크린리더에는 늘 읽힌다).
// **원래 이 자리는 `.pet-circle__label`이었다** — 2026-08-26 머지에서 방 밖 원형 버튼을
// 걷으면서 갈렸다. 크기도 그때 2.15rem → 1.5rem이 됐다(pet.css `.pet-icon`).

export type PetIconName =
  | "seed"
  | "outing"
  // 아래 넷은 2026-08-26 머지에서 더 그렸다(소유자 C의 파일 · 사용자 지시). C의 시안에 없던
  // 자리들이다: 여행일기 보관함 · 마음 친구(챗봇) · 더보기 · 외출 잠김.
  // 규칙은 위 주석 그대로다 — 24×24, 굵고 둥근 획, 외곽선 한 겹 + 안쪽 채색, 색은 CSS가 준다
  | "diary"
  | "chat"
  | "menu"
  | "lock"
  | "chart"
  | "shop"
  | "info"
  | "community"
  | "mission"
  | "meetup"
  | "rest"

export function PetIcon({ name }: { name: PetIconName }) {
  return (
    <svg className="pet-icon" viewBox="0 0 24 24" aria-hidden="true">
      {shapes(name)}
    </svg>
  )
}

function shapes(name: PetIconName) {
  switch (name) {
    // 새싹. 시안 1번 그림이다 — 잎 두 장이 V로 벌어지고 줄기 끝에 씨앗 알이 달린다.
    // **잎이 아이콘 폭을 거의 다 쓴다.** 처음에 작게 그렸다가 26px에서 잎이 줄기 장식처럼
    // 보여 키웠다 — 시안에서도 잎이 그림의 주인공이고 줄기는 실선 한 줄이다
    case "seed":
      return (
        <>
          <path data-f="stem" d="M12 18.2V10" />
          <path data-f="leaf" d="M12 10.2C11 5.9 7.6 3 2.6 2.4c-.7 5.3 3.4 8.7 9.4 7.8" />
          <path data-f="leaf" d="M12 10.2c1-4.3 4.4-7.2 9.4-7.8.7 5.3-3.4 8.7-9.4 7.8" />
          <circle data-f="ball" cx="12" cy="20.4" r="2.3" />
        </>
      )

    // 외출. 시안 첫 묶음의 두 번째 그림(손잡이 달린 가방)이다 — 펫이 무언가를 들고 나간다
    case "outing":
      return (
        <>
          <path data-f="stem" d="M9 8.5V7a3 3 0 0 1 6 0v1.5" />
          <rect data-f="tan" x="3.6" y="8.5" width="16.8" height="11.4" rx="2.2" />
          <rect data-f="latch" x="10.4" y="12.6" width="3.2" height="2.8" rx="0.8" />
        </>
      )

    // 오늘의 활동. 시안 3번 그림 — 막대 셋이 각각 다른 색이고 밑에 받침선이 있다
    case "chart":
      return (
        <>
          <rect data-f="bar1" x="4.6" y="13.2" width="3.8" height="6.2" rx="1" />
          <rect data-f="bar2" x="10.1" y="9.4" width="3.8" height="10" rx="1" />
          <rect data-f="bar3" x="15.6" y="5.6" width="3.8" height="13.8" rx="1" />
          <path data-f="stem" d="M3.2 19.8h17.6" />
        </>
      )

    // 상점. 시안 2번 그림 — 지붕 띠에 24H가 적혀 있다. 글자는 넣지 않았다:
    // 26px로 그려지는 아이콘에서 세 글자는 뭉개지고, 24시간 영업은 이 앱의 사실도 아니다
    case "shop":
      return (
        <>
          <path data-f="roof" d="M5.6 5.2h12.8l2.6 4.4H3z" />
          <rect data-f="tan" x="4.8" y="9.6" width="14.4" height="9.8" rx="1.4" />
          <rect data-f="door" x="9.4" y="13" width="5.2" height="6.4" rx="1.4" />
        </>
      )

    // 펫 정보. 시안 4번 그림 — 동그라미 안 ⓘ다
    case "info":
      return (
        <>
          <circle data-f="cream" cx="12" cy="12" r="8.6" />
          <circle data-f="ink" cx="12" cy="7.9" r="1.15" />
          <path data-f="stem" d="M12 11.2v5.4" />
        </>
      )

    // 커뮤니티. 시안에 없어 같은 규칙으로 그렸다 — 말풍선 하나에 꼬리가 아래로 내려간다
    case "community":
      return (
        <>
          <rect data-f="cream" x="3.2" y="4.6" width="17.6" height="11.6" rx="3.2" />
          <path data-f="cream" d="M8.4 16.2v4.4l4.6-4.4z" />
          <path data-f="stem" d="M7.6 9.2h8.8M7.6 12.2h5.6" />
        </>
      )

    // 미션. 클립보드 + 체크다. 옛 이모지(✅)와 뜻이 같고, 사이드바의 미션 탭도 같은 은유다
    case "mission":
      return (
        <>
          <rect data-f="cream" x="4.6" y="4.4" width="14.8" height="15.6" rx="2.2" />
          <rect data-f="clip" x="9.2" y="2.4" width="5.6" height="3.4" rx="1.2" />
          <path data-f="check" d="M8.6 12.4l2.7 2.7 4.4-5.2" />
        </>
      )

    // 모임. 사람 둘이다 — 오프라인에서 만나는 기능이라 얼굴 둘이 가장 짧은 설명이다.
    // **머리와 몸을 사람별로 한 쌍씩 닫아 둔다.** 처음에는 머리 둘 + 어깨선 둘 + 앞사람 몸
    // 하나였는데, 26px에서 머리 두 개가 "00"으로 붙고 몸이 한 덩어리로 뭉쳤다.
    // 지금은 좌우가 각각 닫힌 도형이라 둘로 갈린다(가운데 약 0.8 좌표가 비어 있다)
    case "meetup":
      return (
        <>
          <circle data-f="cream" cx="7.4" cy="8.4" r="2.7" />
          <path data-f="cream" d="M3.2 19.6c0-2.6 1.9-4.3 4.2-4.3s4.2 1.7 4.2 4.3z" />
          <circle data-f="cream" cx="16.6" cy="8.4" r="2.7" />
          <path data-f="cream" d="M12.4 19.6c0-2.6 1.9-4.3 4.2-4.3s4.2 1.7 4.2 4.3z" />
        </>
      )

    // 여행일기. 펼친 공책이다 — 가운데 접힌 선이 있고 왼쪽 면에 글줄 둘이 그어져 있다.
    // **책등을 세로선 하나로 긋지 않는다.** 26px에서 그 선이 좌우 두 면을 자르는 획으로
    // 보여 "닫힌 책"이 됐다. 지금은 위아래가 살짝 좁아지는 두 면이라 펼친 것으로 읽힌다
    case "diary":
      return (
        <>
          <path data-f="tan" d="M12 5.6C9.8 4.2 6.6 3.6 3.4 3.8v13.6c3.2-.2 6.4.4 8.6 1.8z" />
          <path data-f="tan" d="M12 5.6c2.2-1.4 5.4-2 8.6-1.8v13.6c-3.2-.2-6.4.4-8.6 1.8z" />
          <path data-f="stem" d="M6.2 8.4h3.4M6.2 11.6h3.4" />
        </>
      )

    // 마음 친구(챗봇). 말풍선 + 점 셋이다. 꼬리를 **왼쪽 아래**로 내린다 — 이 화면에서
    // 레일이 오른쪽 끝에 있어 꼬리가 오른쪽이면 방 밖을 가리키는 것으로 보인다
    case "chat":
      return (
        <>
          <path
            data-f="cream"
            d="M20.4 12.4c0 4-3.8 6.9-8.4 6.9-.9 0-1.7-.1-2.5-.3l-4 2 1.1-3.3c-1.5-1.3-2.4-3.1-2.4-5.3 0-4 3.8-6.9 8.4-6.9s7.8 2.9 7.8 6.9z"
          />
          <circle data-f="ink" cx="8.8" cy="12.2" r="1.1" />
          <circle data-f="ink" cx="12.4" cy="12.2" r="1.1" />
          <circle data-f="ink" cx="16" cy="12.2" r="1.1" />
        </>
      )

    // 더보기. 가로 획 셋(햄버거)이다. **점 셋을 쓰지 않았다** — 이 파일의 chat 아이콘이
    // 점 셋을 갖고 있어서 26px에서 둘이 닮는다. 가운데 획만 짧아 목록으로 읽힌다
    case "menu":
      return <path data-f="stem" d="M4.6 7.6h14.8M4.6 12h10.4M4.6 16.4h14.8" />

    // 잠시 쉬어가기 (초승달)
    case "rest":
      return (
        <>
          <path data-f="tan" d="M19.5 13.5A7 7 0 1 1 10.5 4.5A5.5 5.5 0 0 0 19.5 13.5Z" />
        </>
      )

    // 외출 잠김. 자물쇠다 — 몸통 한 칸 + 위로 걸린 고리 + 가운데 열쇠 구멍.
    // 🔒 이모지가 있던 자리다(외출 버튼이 1단계나 친밀도 부족일 때). 같은 줄에 SVG와
    // 이모지가 번갈아 오면 크기·굵기가 어긋나므로 여기까지 같은 세트로 그린다
    case "lock":
      return (
        <>
          <path data-f="stem" d="M8.4 10.2V8a3.6 3.6 0 0 1 7.2 0v2.2" />
          <rect data-f="tan" x="5.4" y="10.2" width="13.2" height="9.4" rx="2.2" />
          <circle data-f="ink" cx="12" cy="14.6" r="1.3" />
          <path data-f="stem" d="M12 15.4v2" />
        </>
      )
  }
}
