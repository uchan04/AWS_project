// 희망 문구 배너의 유일한 출처(SPEC 9절).
//
// 문구는 여기 하드코딩하고 주 1회 단위로만 바뀐다. 매번 무작위로 뽑으면
// 새로고침마다 말이 달라져 "누가 나에게 하는 말"이 아니라 장식으로 읽힌다.
// 대상이 고립은둔청년이므로 격려가 압박이 되지 않게 쓴다 —
// "노력하면 된다"·"용기를 내라"류는 넣지 않는다.
export const HOPE_MESSAGES = [
  "오늘 아무것도 못 했어도 괜찮아요. 여기 온 것만으로 한 걸음이에요.",
  "천천히 가도 늦지 않아요. 속도는 각자 다른 게 맞아요.",
  "말하지 않아도 괜찮아요. 읽기만 해도 이미 함께예요.",
  "누구와도 비교하지 않아요. 어제의 나만 보면 돼요.",
  "잘 지내는 척하지 않아도 돼요. 여기선 그대로여도 돼요.",
] as const

// 주 단위 인덱스. 유닉스 에포크로부터 지난 주 수를 세서 문구 개수로 나눈 나머지다.
// 에포크가 목요일이라 경계도 목요일이지만, 명세가 요구하는 것은 "주 1회 교체"뿐이므로
// 요일을 맞추려고 계산을 늘리지 않는다.
//
// 서버에서만 부른다(커뮤니티 page.tsx는 force-dynamic 서버 컴포넌트다).
// 클라이언트에서 부르면 서버 시각과 어긋나 하이드레이션이 깨질 수 있다.
const WEEK_MS = 7 * 24 * 60 * 60 * 1000

export function hopeMessageOfWeek(now: Date = new Date()): string {
  const week = Math.floor(now.getTime() / WEEK_MS)
  return HOPE_MESSAGES[week % HOPE_MESSAGES.length]
}
