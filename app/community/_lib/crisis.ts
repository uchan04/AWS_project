/**
 * 위기 신호 글·댓글의 처리 정책. **2026-08-25에 팀 결정을 바꿨다.**
 *
 * 이전 결정(2026-08-23): 위기 신호는 **막지 않는다.** 글은 그대로 올라가고 작성자에게만
 * 상담 안내를 돌려줬다. 근거는 "막으면 도움이 가장 필요한 사람의 입을 막는 것이 된다"였다.
 *
 * 바뀐 결정(2026-08-25, 사용자): **저장하지 않는다.** 대신 작성자에게 도움 경로를 안내한다.
 * 커뮤니티에 남기는 대신 도움으로 연결하는 쪽을 택했다.
 *
 * 두 결정 모두 "이 사람을 거절하지 않는다"는 같은 목적을 갖는다. 그래서 구현에 조건이 붙는다.
 *
 * 1. **실패가 아니라 안내다.** 400이 아니라 200으로 준다. 400은 화면에서 빨간 오류로
 *    읽히고, 지금 이 사람에게 필요한 것은 거절 통보가 아니다.
 * 2. **쓴 글을 지우지 않는다.** 화면은 입력을 그대로 두고 안내만 얹는다. 어렵게 쓴 글이
 *    사라지면 안내가 벌처럼 읽힌다.
 * 3. **비난하는 말을 쓰지 않는다.** "차단", "부적절", "규정 위반" 같은 말을 쓰지 않는다.
 *    거절이 아니라 다른 길을 알려주는 톤이어야 한다(`npm run check:community`가 검사한다).
 */

import { CRISIS_HOTLINE, isCrisis } from "@/lib/safety"

/**
 * 저장하지 않았을 때 작성자에게 보여줄 문구.
 *
 * **`lib/safety.ts`의 `CRISIS_POST_NOTICE`를 쓰지 않는다.** 그 문구는 "올라갔어요"로
 * 시작한다 — 글이 실제로 저장되던 시절의 문장이라, 지금 그대로 쓰면 올리지 않은 글을
 * 올렸다고 알리는 셈이 된다. 그 파일은 E 소유라 고치지 않고 여기에 새로 둔다.
 *
 * 번호를 문장에 넣지 않는다 — `app/components/CrisisNotice.tsx`의 전화 버튼이 이미 띄운다.
 */
export const CRISIS_BLOCKED_NOTICE =
  "이 글은 아직 올리지 않았어요. 쓴 내용은 그대로 두었으니 사라지지 않아요. " +
  "지금 마음이 많이 무거운 것 같아서, 커뮤니티보다 먼저 닿을 수 있는 곳을 하나 알려드릴게요."

export type CrisisBlockedPayload = {
  crisisBlocked: true
  notice: string
}

/**
 * 위기 신호로 저장을 멈췄을 때의 응답 본문. 글 라우트와 댓글 라우트가 같은 것을 쓴다 —
 * 두 곳이 다른 모양을 주면 화면이 각각 처리해야 하고, 한쪽만 고쳐지기 쉽다.
 *
 * `post`·`comment` 키를 담지 않는다. 저장된 것이 없다는 사실이 응답 모양으로 드러나야
 * 화면이 실수로 목록에 밀어 넣지 않는다.
 */
export function crisisBlockedPayload(): CrisisBlockedPayload {
  return { crisisBlocked: true, notice: CRISIS_BLOCKED_NOTICE }
}

/** 안내 문구에 들어가면 안 되는 말. 거절로 읽히는 어휘다(`check:community`가 검사한다). */
export const BLAMING_WORDS = ["차단", "부적절", "규정", "위반", "금지", "삭제되었"]

/** 전화 안내가 가리키는 번호. 화면이 아니라 검사에서 쓴다 — 번호가 갈리지 않게. */
export const CRISIS_BLOCKED_HOTLINE = CRISIS_HOTLINE

/* ────────────────────────────────────────────────────────────
 * 차단용 판정 (2026-08-25 추가)
 *
 * **`isCrisis()`와 용도가 다르다.** 그쪽은 주석이 밝히듯 "오탐을 허용하는 쪽으로"
 * 설계됐고, 결과가 *안내를 한 번 더 띄우는 것*일 때는 그 편향이 옳다. 놓치는 것보다
 * 한 번 더 묻는 쪽이 낫기 때문이다.
 *
 * 그런데 2026-08-25에 그 결과가 **"글이 저장되지 않는 것"** 으로 바뀌면서 오탐의 대가가
 * 달라졌다. 같은 편향을 그대로 쓰면 실측(2026-08-25)에서 이런 글이 전부 막힌다.
 *
 *   "친구가 자살했다는 소식을 들었다"   ← 사별
 *   "자살 예방 교육을 들었다"          ← 공익·교육
 *   "자살률 기사를 봤다"               ← 보도
 *   "죽고 싶을 만큼 웃겼다"            ← 비유
 *   "살기 싫을 만큼 더운 날씨"          ← 비유
 *
 * 사별한 사람의 글이 막히는 것은 이 서비스가 가장 하면 안 되는 일에 가깝다.
 * 그래서 **차단은 더 좁은 판정으로 가른다.** `isCrisis()`는 그대로 두고(안내용으로 계속
 * 쓴다) 그 위에 제외 규칙을 얹는다. `lib/safety.ts`는 E 소유라 고치지 않는다.
 *
 * **기울기는 미탐 쪽이다.** 놓치면 글이 올라가고(안내는 여전히 뜬다), 잘못 막으면
 * 사별한 사람의 글이 사라진다. 애매하면 통과시킨다.
 * ──────────────────────────────────────────────────────────── */

/**
 * 문장 단위로 자른다. 제외 규칙을 글 전체에 걸면 긴 글에서 엉뚱하게 샌다 —
 * 앞 문단의 "친구가"가 뒷 문단의 고백을 통과시켜 버린다. 판정은 문장 안에서만 본다.
 */
function sentences(text: string): string[] {
  return text
    .split(/[.!?\r\n]+/)
    .map((s) => s.trim())
    .filter(Boolean)
}

/**
 * 3인칭 서술. 위기 표현의 주체가 글쓴이가 아니다.
 *
 * 조사를 요구한다 — `사람`만 보면 "사람들이 싫다"까지 걸린다.
 */
const THIRD_PERSON =
  /(친구|주인공|누군가|누가|동생|형|누나|오빠|언니|엄마|아빠|아버지|어머니|부모|가족|지인|동료|선배|후배|이웃|사람|그녀|그분)(이|가|는|도|의|를|을)/

/**
 * 전언·사별. "들었다"만 보면 안 된다 — **"죽고 싶다는 생각이 들었다"가 같이 걸린다.**
 * 그건 1인칭 고백이다. 그래서 앞에 전언을 뜻하는 명사가 붙은 경우만 본다.
 */
const HEARSAY = /(소식|이야기|얘기|말|소문|고백|글)(을|를|이|가)?\s*(들었|듣고|접했|전해|봤|보고)/

/** 보도·교육·통계. 이 단어들이 있으면 위기 표현이 소재이지 고백이 아니다. */
const REPORT = /기사|뉴스|보도|예방|캠페인|교육|강의|통계|률|율|다큐|영화|드라마|소설|웹툰|장면/

/**
 * 비유. "죽고 싶을 만큼 웃겼다"처럼 앞부분이 뒤의 말을 수식한다.
 *
 * **완벽하지 않다.** "죽고 싶을 만큼 힘들다"는 진짜 고통의 표현인데 같은 형태라 함께
 * 통과한다. 뒤에 오는 말이 농담인지 고통인지는 정규식이 가를 수 없다. 미탐 쪽으로 둔다.
 */
const SIMILE = /(싶|싫)을\s*(만큼|정도)/

/** 과거 회상. 이것만으로는 제외하지 않는다 — 아래 RECOVERED와 함께 있을 때만이다. */
const PAST_RECALL = /(예전|그때|옛날|한때|과거|어릴\s*때)(에|엔|는|가|도|을|를)?/

/**
 * 회복 서사의 뒷부분. `PAST_RECALL`과 짝일 때만 제외한다.
 *
 * 둘을 함께 요구하는 이유는 "예전에도 죽고 싶었고 지금도 죽고 싶다"를 통과시키지 않기
 * 위해서다. 회상 표지만 보고 제외하면 그 문장이 새어나간다.
 */
const RECOVERED = /(지금|이제|요즘)(은|이|도|에는)?\s*(괜찮|나아|낫|좋아|버티|견디|살아|나았)/

/**
 * `자살`·`자해`가 1인칭 의도로 쓰였는지.
 *
 * 이 두 단어는 `lib/safety.ts`에서 **주어도 어미도 보지 않고** 단어 존재만으로 잡는다
 * (다른 12개는 최소한 `~고 싶`·`~어 버리` 같은 어미를 요구한다). 실측한 오탐이 전부
 * 여기서 나왔으므로, 이 둘만 근거일 때는 의도 표현을 따로 요구한다.
 */
const SELF_HARM_INTENT = /(자살|자해)\s*(하고\s*싶|하려|할\s*(것|거|까)|하겠|한다면|해\s*버리)/

/**
 * 이 문장의 위기 판정이 `자살`·`자해` 단어 하나에만 걸려 있는지.
 *
 * 패턴 목록을 여기에 다시 적지 않는다 — `lib/safety.ts`와 두 벌이 되면 한쪽만 고쳐져
 * 조용히 갈라진다. 대신 그 두 단어를 지우고 다시 물어본다. 여전히 위기면 다른 근거가
 * 있다는 뜻이고, 아니면 근거가 그 단어뿐이었다는 뜻이다.
 */
function onlyFromBareNoun(sentence: string): boolean {
  return !isCrisis(sentence.replace(/자살|자해/g, ""))
}

/** 문장 하나가 저장을 막을 만한 1인칭 현재의 위기 표현인지. */
function sentenceBlocks(sentence: string): boolean {
  if (!isCrisis(sentence)) return false

  // 1. 주체가 글쓴이가 아니거나, 위기 표현이 소재로 등장한 경우
  if (THIRD_PERSON.test(sentence)) return false
  if (HEARSAY.test(sentence)) return false
  if (REPORT.test(sentence)) return false

  // 2. 비유
  if (SIMILE.test(sentence)) return false

  // 3. 과거 회상 + 회복. 회복 서사가 막히면 안 된다
  if (PAST_RECALL.test(sentence) && RECOVERED.test(sentence)) return false

  // 자살·자해 단독은 차단 근거가 되지 못한다. 의도 표현이 함께 있어야 한다
  if (onlyFromBareNoun(sentence) && !SELF_HARM_INTENT.test(sentence)) return false

  return true
}

/**
 * **저장을 막을지** 판정한다. 안내를 띄울지는 `lib/safety.ts`의 `isCrisis()`가 정한다.
 *
 * `isCrisis()`가 true인 것 중에서만 true가 될 수 있다 — 이 함수가 판정을 넓히는 일은
 * 없다. 하는 일은 좁히는 것뿐이다.
 *
 * 문장 단위로 본다. 한 문장이라도 막을 만하면 막는다. 문장으로 잘랐을 때 아무것도
 * 걸리지 않는데 글 전체로는 걸리는 경우(위기 표현이 문장 경계를 넘어간 경우)에는
 * 글 전체를 한 문장처럼 본다 — 자르는 방식 때문에 판정이 새면 안 된다.
 */
export function blocksPosting(text: string): boolean {
  if (!isCrisis(text)) return false

  const parts = sentences(text)
  if (parts.some(sentenceBlocks)) return true
  if (parts.some(isCrisis)) return false

  return sentenceBlocks(text)
}
