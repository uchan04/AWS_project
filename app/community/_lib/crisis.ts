/**
 * 위기 신호 글·댓글의 처리 정책. **2026-08-25에 팀 결정을 바꿨다.**
 *
 * 이전 결정(2026-08-23): 위기 신호는 **막지 않는다.** 글은 그대로 올라가고 작성자에게만
 * 상담 안내를 돌려줬다. 근거는 "막으면 도움이 가장 필요한 사람의 입을 막는 것이 된다"였다.
 *
 * 바뀐 결정(2026-08-25, 사용자): **저장하지 않는다.** 대신 작성자에게 도움 경로를 안내한다.
 * 커뮤니티에 남기는 대신 도움으로 연결하는 쪽을 택했다.
 *
 * 두 결정 모두 "이 사람을 거절하지 않는다"는 같은 목적을 갖는다. 그래서 구현에 조건이 붙는다.
 *
 * 1. **실패가 아니라 안내다.** 400이 아니라 200으로 준다. 400은 화면에서 빨간 오류로
 *    읽히고, 지금 이 사람에게 필요한 것은 거절 통보가 아니다.
 * 2. **쓴 글을 지우지 않는다.** 화면은 입력을 그대로 두고 안내만 얹는다. 어렵게 쓴 글이
 *    사라지면 안내가 벌처럼 읽힌다.
 * 3. **비난하는 말을 쓰지 않는다.** "차단", "부적절", "규정 위반" 같은 말을 쓰지 않는다.
 *    거절이 아니라 다른 길을 알려주는 톤이어야 한다(`npm run check:community`가 검사한다).
 */

import { CRISIS_HOTLINE } from "@/lib/safety"

/**
 * 저장하지 않았을 때 작성자에게 보여줄 문구.
 *
 * **`lib/safety.ts`의 `CRISIS_POST_NOTICE`를 쓰지 않는다.** 그 문구는 "올라갔어요"로
 * 시작한다 — 글이 실제로 저장되던 시절의 문장이라, 지금 그대로 쓰면 올리지 않은 글을
 * 올렸다고 알리는 셈이 된다. 그 파일은 E 소유라 고치지 않고 여기에 새로 둔다.
 *
 * 번호를 문장에 넣지 않는다 — `app/components/CrisisNotice.tsx`의 전화 버튼이 이미 띄운다.
 */
export const CRISIS_BLOCKED_NOTICE =
  "이 글은 아직 올리지 않았어요. 쓴 내용은 그대로 두었으니 사라지지 않아요. " +
  "지금 마음이 많이 무거운 것 같아서, 커뮤니티보다 먼저 닿을 수 있는 곳을 하나 알려드릴게요."

export type CrisisBlockedPayload = {
  crisisBlocked: true
  notice: string
}

/**
 * 위기 신호로 저장을 멈췄을 때의 응답 본문. 글 라우트와 댓글 라우트가 같은 것을 쓴다 —
 * 두 곳이 다른 모양을 주면 화면이 각각 처리해야 하고, 한쪽만 고쳐지기 쉽다.
 *
 * `post`·`comment` 키를 담지 않는다. 저장된 것이 없다는 사실이 응답 모양으로 드러나야
 * 화면이 실수로 목록에 밀어 넣지 않는다.
 */
export function crisisBlockedPayload(): CrisisBlockedPayload {
  return { crisisBlocked: true, notice: CRISIS_BLOCKED_NOTICE }
}

/** 안내 문구에 들어가면 안 되는 말. 거절로 읽히는 어휘다(`check:community`가 검사한다). */
export const BLAMING_WORDS = ["차단", "부적절", "규정", "위반", "금지", "삭제되었"]

/** 전화 안내가 가리키는 번호. 화면이 아니라 검사에서 쓴다 — 번호가 갈리지 않게. */
export const CRISIS_BLOCKED_HOTLINE = CRISIS_HOTLINE
