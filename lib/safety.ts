/**
 * 자해·자살 신호.
 *
 * 한국어 구어 표현을 그대로 잡는다. 띄어쓰기는 `\s*`로 흡수한다 — "죽고싶다"와
 * "죽고 싶다"가 같은 빈도로 쓰인다.
 *
 * 넣지 않은 것과 이유:
 * - 맨 `끝내고 싶`: "과제를 다 끝내고 싶다"가 압도적으로 흔하다. `삶|인생|이번 생|모든 걸`이
 *   앞에 붙는 형태만 잡는다. `다 끝내`도 같은 이유로 넣지 않는다
 * - `죽을까`: "엄마가 죽을까 봐 무섭다"를 잡는다. 이건 타인에 대한 걱정이라 고정 응답이
 *   오히려 말을 잘못 받는다. `죽고 싶`이 본래 표현을 이미 덮는다
 * - 맨 `힘들`, `우울`: 이 서비스에서는 이게 정상 대화다. 여기에 상담 카드를 띄우면
 *   카드가 배경 소음이 되고, 정작 필요한 순간에 안 읽힌다
 */
const CRISIS_PATTERNS: readonly RegExp[] = [
  /죽고\s*싶/,
  /죽어\s*버리/,
  // "낫다"와 "나을"은 다른 음절로 시작한다. 둘 다 적는다
  /죽는\s*게\s*(낫|나을|나아)/,
  /자살/,
  /자해/,
  /목숨을\s*끊/,
  /목을\s*매/,
  /(삶|인생|이번\s*생|모든\s*걸)\s*(을|를)?\s*끝내/,
  /사라지고\s*싶/,
  /사라져\s*버리/,
  /없어지고\s*싶/,
  /살기\s*싫/,
  /살고\s*싶지\s*않/,
  /태어나지\s*(않았으면|말았)/,
]

/** 자해·자살 신호가 있으면 true. 오탐을 허용하는 쪽으로 판정한다. */
export function isCrisis(text: string): boolean {
  return CRISIS_PATTERNS.some((re) => re.test(text))
}

/**
 * 타인을 향한 공격. **이것만 게시를 막는다.**
 *
 * `lib/diagnosis/reason.ts`의 `BANNED`(낙인 단어)를 여기에 쓰지 않는다. 그 목록은
 * *서비스가 사용자를 규정하는 것*을 막는 장치다. 사용자가 자기 상태를 스스로
 * "나는 고립됐다"고 말하는 것은 막을 이유가 없고, 막으면 털어놓는 공간이라는
 * 전제가 무너진다.
 *
 * **2인칭 지시가 있을 때만 잡는다.** 욕설 자체를 막지 않는다 — "씨발 오늘 너무
 * 힘들었다"는 대상 없는 자기 발화이고, "내 인생 쓰레기 같아"는 자기 비하다. 털어놓는
 * 공간에서 이 둘을 차단하면 사람이 떠난다. 차단은 남을 향한 말에만 쓴다.
 *
 * ponytail: 자해 *방법* 서술은 따로 판정하지 않는다. 정규식으로 "죽고 싶다"(고백)와
 * "이렇게 하면 죽는다"(방법)를 가르면 오분류가 생기고, 그 오분류의 대가가 고백을
 * 차단하는 것이다. 신고 기능이 들어오면 사람이 판정하는 쪽으로 올린다.
 */
const SLUR = "씨발|시발|병신|지랄|개새|새끼|미친년|미친놈|좆|썅|찌질|한심|꺼져|닥쳐"

// 2인칭 지시어. **한국어에서 부분 문자열로 새는 것을 막는 가드가 핵심이다.**
// - `너(?!무)`: "오늘 너무 한심했다"가 자기 비하인데 `너`+`한심`으로 걸린다
// - `(?<![가-힣])니가`: "어머니가 죽었으면"이 `니가`+죽음으로 걸린다.
//   가족 이야기는 FAMILY_LIVING 유형의 핵심 주제라 이걸 막으면 서비스가 망가진다
const SECOND_PERSON = "너(?!무)|넌|(?<![가-힣])니가|(?<![가-힣])네가|당신|이새끼|저새끼|저놈|저년"

const ABUSE_PATTERNS: readonly RegExp[] = [
  // 호격 조사가 **띄어쓰기 없이** 붙은 욕설 — "병신아", "새끼야". 대상이 있는 말이다.
  // 공백을 허용하면 "씨발 아 진짜"(대상 없는 혼잣말)가 걸린다
  new RegExp(`(${SLUR})(아|야)(?![가-힣])`),
  // 2인칭과 욕설이 한 문장 안에 같이 있는 경우(양방향). 20자 이내로 제한한다 —
  // 문장이 길어지면 둘이 서로 무관한 자리에 있을 확률이 커진다
  new RegExp(`(${SECOND_PERSON})[^.!?\\n]{0,20}(${SLUR})`),
  new RegExp(`(${SLUR})[^.!?\\n]{0,20}(${SECOND_PERSON})`),
  // 2인칭을 향한 죽음 명령·소망. "너 죽어", "네가 죽었으면"
  new RegExp(`(${SECOND_PERSON})\\s*(가|는|도)?\\s*죽(어|여|었으면)`),
]

/** 타인 공격·모욕이 있으면 true. 게시를 차단하는 유일한 기준이다. */
export function containsAbuse(text: string): boolean {
  return ABUSE_PATTERNS.some((re) => re.test(text))
}

